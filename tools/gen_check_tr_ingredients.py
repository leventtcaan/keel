#!/usr/bin/env python3
"""Writes tools/check_tr_ingredients.sql from data/food/tr-dishes.json (K-1213): a read-only query that lists every ingredient
description (and its alternatives and FDC id) of the Turkish dishes with whether nutrition.food has it, and by which source.
Run after the dishes file changes:  python3 tools/gen_check_tr_ingredients.py"""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
dishes = json.loads((root / "data/food/tr-dishes.json").read_text(encoding="utf-8"))["dishes"]
rows = {}
for dish in dishes:
    for ingredient in dish["ingredients"]:
        names = [ingredient["food"], *ingredient.get("or", [])]
        for rank, name in enumerate(names):
            entry = rows.setdefault(name, {"fdc": ingredient.get("fdcId") if rank == 0 else None, "rank": rank, "dishes": set()})
            entry["dishes"].add(dish["id"])


def literal(text):
    return "'" + text.replace("'", "''") + "'"


values = ",\n".join(
    f"    ({literal(name)}, {entry['fdc'] if entry['fdc'] else 'null'}, {entry['rank']}, {len(entry['dishes'])})"
    for name, entry in sorted(rows.items(), key=lambda item: (item[1]["rank"], item[0])))
sql = f"""-- Read-only (K-1213): does nutrition.food have every ingredient of the Turkish dishes? Generated by tools/gen_check_tr_ingredients.py
-- from data/food/tr-dishes.json; run it on the server:  psql -f tools/check_tr_ingredients.sql
-- wanted: the description, its FDC id when the file has one, 0 = the dish's own description and 1.. = an alternative, the dishes using it.
-- found: how many rows have that description (and which sources), and whether the FDC id's row is there. A dish is worked out when,
-- for each of its ingredients, the id or one of the descriptions is found: look for rows where rank = 0 and nothing is found, then
-- check that an alternative (rank above 0) is.
with wanted (description, fdc_id, rank, dishes) as (
    values
{values}
)
select w.rank, w.description, w.fdc_id, w.dishes,
       (select string_agg(distinct f.source, ', ' order by f.source) from nutrition.food f
         where f.name = w.description and f.dataset = 'FDC' and f.source in ('FOUNDATION', 'SR_LEGACY', 'FNDDS')) as found_by_description,
       case when w.fdc_id is null then null
            else exists (select 1 from nutrition.food f where f.id = 'fdc:' || w.fdc_id) end as found_by_id
from wanted w
order by (select count(*) from nutrition.food f where f.name = w.description and f.dataset = 'FDC') = 0 desc, w.rank, w.description;
"""
(root / "tools/check_tr_ingredients.sql").write_text(sql, encoding="utf-8")
print(len(rows), "descriptions")
